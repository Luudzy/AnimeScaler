import { readFile, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';
import { fileURLToPath } from 'node:url';
import { resolve, relative } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));

export async function buildContent({ write = true } = {}) {
  const modules = new Map(), visiting = new Set(), sections = [];
  // Content sources use named static imports and declaration exports.
  // Keep module scopes separate; reject unsupported syntax rather than changing its semantics.
  async function visit(path) {
    if (visiting.has(path)) throw new Error(`Circular content dependency: ${path}`);
    if (modules.has(path)) return modules.get(path);
    if (!path.startsWith('src/')) throw new Error(`Content dependency outside src/: ${path}`);
    visiting.add(path);
    let source = await readFile(resolve(root, path), 'utf8');
    const bindings = [];
    const imports = [...source.matchAll(/^import\s+\{([^}]+)\}\s+from\s+(['"])([^'"]+)\2\s*;[ \t]*\r?$/gm)];
    for (const [statement, names, , specifier] of imports) {
      if (!specifier.startsWith('.')) throw new Error(`Nonlocal content import: ${specifier}`);
      const dependency = fileURLToPath(new URL(specifier, new URL(path, new URL('../', import.meta.url))));
      const relativePath = relative(root, dependency).replaceAll('\\', '/');
      const module = await visit(relativePath);
      const fields = names.split(',').map(name => name.trim().replace(/\s+as\s+/, ': ')).join(', ');
      bindings.push(`const { ${fields} } = ${module};`);
      source = source.replace(statement, '');
    }
    const exports = [];
    source = source.replace(/^export\s+((?:async\s+)?function\*?|class|const)\s+([A-Za-z_$][\w$]*)/gm,
      (_, kind, name) => { exports.push(name); return `${kind} ${name}`; });
    if (/^\s*(?:import\s+(?!\()|export\s+)/m.test(source) || /\bimport\.meta\b/.test(source)) {
      throw new Error(`Unsupported content module syntax: ${path}`);
    }
    const module = `contentModule${modules.size}`;
    modules.set(path, module);
    visiting.delete(path);
    sections.push(`// ${path}\nconst ${module} = (() => {\n${bindings.join('\n')}\n${source}\nreturn { ${exports.join(', ')} };\n})();`);
    return module;
  }
  await visit('src/content/bootstrap.js');
  const output = `// Generated by npm run build:content. Edit src/content/bootstrap.js and its source modules.\n(() => {\n'use strict';\n${sections.join('\n\n')}\n})();\n`;
  new Script(output, { filename: 'content-bootstrap.js' });
  if (write) await writeFile(resolve(root, 'content-bootstrap.js'), output);
  return output;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildContent();
}
